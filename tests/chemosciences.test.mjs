import assert from 'node:assert/strict';
import {buildEdges,filterRecords,selectGraphNodes,safeUrl,escapeHtml} from '../assets/js/chemosciences-core.js';
const domain={id:'taste',kind:'domain',label:'Taste',linkable:false};
const concept={id:'pou2f3',kind:'mechanism',label:'POU2F3 cell programs',linkable:true};
const n=(id,concepts=[domain],weeks=['2026-10-26'])=>({id,title:`Paper ${id}`,authors:['Smith AB'],journal:'Small journal',score:60,concepts,weeks,selected_weeks:weeks,editor_weeks:[]});
assert.equal(buildEdges([n('1'),n('2')]).length,0,'Sharing only a sense does not create a biological edge');
assert.equal(buildEdges([n('1',[domain,concept]),n('2',[concept])]).length,1,'Specific mechanisms create cross-domain links');
assert.equal(buildEdges([n('1'),n('2')],'author').length,1);
const nodes=[n('1',[domain,concept]),n('2',[concept],['2026-10-19']),n('3',[domain],['2026-10-19'])];
assert.deepEqual(selectGraphNodes(nodes,['2026-10-26'],false,'all','',false,'concept').nodes.map(n=>n.id),['1']);
assert.deepEqual(selectGraphNodes(nodes,['2026-10-26'],false,'all','',true,'concept').nodes.map(n=>n.id),['1','2']);
assert.equal(selectGraphNodes(nodes,[],false,'all','',false,'concept').nodes.length,0);
assert.equal(safeUrl('javascript:alert(1)'),'#');
assert.equal(escapeHtml('<script>'),'&lt;script&gt;');
const record={paper:{title:'A taste paper',abstract:'SOX2',authors:['Smith AB']},analysis:{eligible:true,concepts:[domain]},reading_list:false};
assert.equal(filterRecords([record],'all','',false).length,0);
assert.equal(filterRecords([record],'taste','sox2',true).length,1);
globalThis.HTMLElement=class {};
globalThis.customElements={define(){}};
const {coverageForRun,rangeLabel}=await import('../assets/js/week-calendar.js');
assert.deepEqual(coverageForRun('2026-11-02'),{id:'2026-11-02',start:'2026-10-26',end:'2026-11-01',inferred:true});
assert.equal(coverageForRun('2026-03-09').start,'2026-03-02','Coverage uses UTC date arithmetic through DST');
assert.match(rangeLabel(coverageForRun('2026-11-02')),/Oct 26.*Nov 1/);
console.log('Chemosciences filtering, relationship, security, and weekly calendar tests passed.');
